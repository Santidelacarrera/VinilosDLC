create or replace function public.reserve_musicbrainz_call()
returns boolean language plpgsql security invoker set search_path = public as $$
declare previous timestamptz;
begin
  perform pg_advisory_xact_lock(78114217);
  select last_call_at into previous from public.external_api_throttle where provider = 'musicbrainz';
  if previous is not null and previous > now() - interval '1 second' then
    return false;
  end if;
  insert into public.external_api_throttle(provider,last_call_at) values ('musicbrainz',now())
    on conflict(provider) do update set last_call_at = excluded.last_call_at;
  return true;
end;
$$;
revoke all on function public.reserve_musicbrainz_call() from public, anon, authenticated;
grant execute on function public.reserve_musicbrainz_call() to service_role;

create or replace function public.import_musicbrainz_release(p_release jsonb)
returns bigint language plpgsql security invoker set search_path = public as $$
declare album_key bigint; item jsonb; expected_count integer;
begin
  if nullif(p_release->>'musicbrainzId','') is null or nullif(p_release->>'title','') is null
    or nullif(p_release->>'artist','') is null then
    raise exception 'invalid release';
  end if;
  expected_count := jsonb_array_length(coalesce(p_release->'tracks','[]'::jsonb));
  if expected_count < 1 or expected_count > 200 then raise exception 'invalid track count'; end if;
  if exists(select 1 from public.albums where musicbrainz_id = (p_release->>'musicbrainzId')::uuid) then
    raise unique_violation using message = 'release already imported';
  end if;
  insert into public.albums(title,artist,year,discos,tracklist,musicbrainz_id,release_group_id,
    barcode,label,catalog_number,country,format,metadata_source)
  values (p_release->>'title',p_release->>'artist',nullif(p_release->>'year','')::integer,
    greatest(1,least(10,coalesce((p_release->>'discCount')::integer,1))),
    (select jsonb_agg(value->>'title' order by ord) from jsonb_array_elements(p_release->'tracks') with ordinality as t(value,ord)),
    (p_release->>'musicbrainzId')::uuid,nullif(p_release->>'releaseGroupId','')::uuid,
    nullif(p_release->>'barcode',''),nullif(p_release->>'label',''),
    nullif(p_release->>'catalogNumber',''),nullif(p_release->>'country',''),
    nullif(p_release->>'format',''),'MusicBrainz') returning id into album_key;
  for item in select value from jsonb_array_elements(p_release->'tracks') as t(value) loop
    insert into public.tracks(album_id,disc_number,track_number,position_label,title,artist,duration_ms,
      musicbrainz_recording_id,isrc,metadata_source)
    values(album_key,(item->>'discNumber')::integer,(item->>'trackNumber')::integer,
      nullif(item->>'positionLabel',''),item->>'title',nullif(item->>'artist',''),
      nullif(item->>'durationMs','')::integer,nullif(item->>'recordingId','')::uuid,
      nullif(item->>'isrc',''),'MusicBrainz');
  end loop;
  return album_key;
end;
$$;
revoke all on function public.import_musicbrainz_release(jsonb) from public, anon, authenticated;
