create or replace function public.sync_manual_tracks()
returns trigger language plpgsql security invoker set search_path = public as $$
begin
  if new.metadata_source = 'MusicBrainz' then return new; end if;
  if tg_op = 'UPDATE' and new.tracklist is not distinct from old.tracklist then return new; end if;
  if tg_op = 'UPDATE' and exists(select 1 from public.tracks where album_id = new.id and rights_status = 'AUTHORIZED') then
    raise exception 'remove authorized audio before replacing the tracklist';
  end if;
  delete from public.tracks where album_id = new.id;
  insert into public.tracks(album_id,disc_number,track_number,title,artist,metadata_source)
  select new.id,1,ordinality::integer,value,new.artist,'Manual'
    from jsonb_array_elements_text(new.tracklist) with ordinality as t(value,ordinality);
  return new;
end;
$$;
drop trigger if exists albums_sync_manual_tracks on public.albums;
create trigger albums_sync_manual_tracks after insert or update of tracklist on public.albums
  for each row execute function public.sync_manual_tracks();

